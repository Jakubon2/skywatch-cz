"""One-off: generate VAPID keys for Web Push and append them to the repo's .env.

    cd backend && .venv/bin/python vapid_keys.py [--subject mailto:you@example.com]

Refuses to overwrite existing keys: rotating them invalidates every browser subscription.
"""

import argparse
import base64

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

from config import ROOT

ENV = ROOT / ".env"


def b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def main():
    parser = argparse.ArgumentParser()
    # Push services contact this address if the app misbehaves; must be mailto: or https:.
    parser.add_argument("--subject", default="mailto:skywatch@example.com")
    args = parser.parse_args()

    text = ENV.read_text(encoding="utf-8") if ENV.exists() else ""
    if any(line.split("=", 1)[0] == "VAPID_PRIVATE_KEY" and line.split("=", 1)[1].strip()
           for line in text.splitlines() if "=" in line):
        raise SystemExit(f"VAPID_PRIVATE_KEY already set in {ENV}, not overwriting.")

    key = ec.generate_private_key(ec.SECP256R1())
    private = b64url(key.private_numbers().private_value.to_bytes(32, "big"))
    public = b64url(key.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))

    # Drop empty placeholders (e.g. copied from .env.example), then append the real values.
    lines = [line for line in text.splitlines() if line.split("=", 1)[0] not in
             ("VAPID_PUBLIC_KEY", "VAPID_PRIVATE_KEY", "VAPID_SUBJECT")]
    lines += ["", "# Web Push (generated by backend/vapid_keys.py)",
              f"VAPID_PUBLIC_KEY={public}", f"VAPID_PRIVATE_KEY={private}", f"VAPID_SUBJECT={args.subject}"]
    ENV.write_text("\n".join(lines).lstrip("\n") + "\n", encoding="utf-8")
    print(f"VAPID keys written to {ENV}")


if __name__ == "__main__":
    main()
